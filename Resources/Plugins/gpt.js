const axios = require('axios')

module.exports = {
  command: ['gpt','chatgpt','gemini','deepseek','chatbot','ai'],
  description: "AI Chat using MEGAN",

  execute: async (sock, msg, args) => {
    const jid = msg.key.remoteJid
    const query = args.join(' ').trim()
    
    if (!query) {
      return await sock.sendMessage(jid, { 
        text: "┌─⊷ ◇ BREAKER AI ◇\n│ Usage: .gpt hello how are you?\n│ .ai write me a love letter\n└─⊷" 
      }, { quoted: msg })
    }
    
    try {
      // Show typing... so user knows bot is working
      await sock.sendPresenceUpdate('composing', jid)

      let ans = null

      // 1. Try MEGAN API first (your main API)
      if (typeof global.MEGAN_AI === 'function') {
        try {
          ans = await global.MEGAN_AI(query)
        } catch (e) {
          console.log("[MEGAN_AI FAIL]", e.message)
        }
      }
      
      // 2. Fallback if MEGAN fails
      if (!ans || ans.includes("Offline") || ans.includes("No response")) {
        console.log("Trying fallback Zenith API...")
        const res = await axios.get(`https://api.zenith.org/api/ai?text=${encodeURIComponent(query)}`, { timeout: 15000 })
        ans = res.data?.result || res.data?.response || res.data?.answer
      }

      // 3. Final fallback
      if (!ans) ans = "❌ AI is busy, try again in 10 seconds."

      await sock.sendMessage(jid, { 
        text: `┌─⊷ ◇ BREAKER AI ◇\n│ ${ans}\n└─⊷\n\n_Generated by MEGAN_` 
      }, { quoted: msg })

    } catch (e) {
      console.log("[GPT ERROR]", e.message)
      await sock.sendMessage(jid, { 
        text: `┌─⊷ ◇ AI ERROR ◇\n│ ${e.message}\n│ Try again later\n└─⊷` 
      }, { quoted: msg })
    }
  }
}
